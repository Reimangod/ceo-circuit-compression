"""Build English documentation views from saved selections; no quantum imports."""
import argparse
from collections import Counter
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ("cnot", "cnot_depth", "parameters", "total_depth")
LABELS = {"LiH": "LiH", "HF": "HF", "BeH2": "BeH₂", "N2": "N₂"}


def generated_files(root=ROOT):
    root = Path(root)
    rows = json.loads((root / "data/metadata/report-selection.json").read_text())["current"]
    assert len(rows) == 22
    assert Counter(r["molecule"] for r in rows) == {"LiH": 8, "HF": 2, "BeH2": 8, "N2": 4}
    assert len({(r["molecule"], r["distance_A"]) for r in rows}) == 22
    for row in rows:
        assert row["child_energy_Ha"] <= row["ceo_energy_Ha"] + 1e-9
        assert row["child"]["cnot"] < row["common_resources"]["cnot"]
        assert row["child"]["cnot_depth"] <= row["common_resources"]["cnot_depth"]

    lines = [
        "# Current-policy results", "",
        "These are the 22 condition-wise largest total CNOT reductions selected from",
        "the saved current-policy runs. They are descriptive recorded comparisons,",
        "not guarantees for every start or evidence of matched-work superiority.", "",
        "All conditions use the full-orbital STO-3G problem. The four resource changes",
        "in one row belong to the same actual circuit pair. `Start / compare` identifies",
        "the construction source and the saved CEO comparison step, respectively.", "",
        "Resource arrows run from the raw CEO decomposition to the compressed circuit.",
        "Total reduction therefore includes the common reference-input simplification.",
        "Energy change is `E_compressed - E_comparator`, in mHa. Tiny positive values",
        "are retained and fall within the registered 1e-9 Ha tolerance.", "",
        "| Molecule | Bond length / Å | Start / compare | Energy change / mHa | CNOT count | CNOT depth | Parameters | Total depth | Total CNOT reduction |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    order = {mol: i for i, mol in enumerate(("LiH", "HF", "BeH2", "N2"))}
    for row in sorted(rows, key=lambda r: (order[r["molecule"]], r["distance_A"])):
        values = [LABELS[row["molecule"]], f'{row["distance_A"]:.2f}',
                  f'{row["root_step"]} / {row["comparator_step"]}',
                  f'{row["delta_energy_Ha"] * 1000:+.6g}']
        values += [f'{row["ceo"][key]} → {row["child"][key]}' for key in METRICS]
        values += [f'{row["reduction_pct"]["cnot"]:.1f}%']
        lines.append("| " + " | ".join(values) + " |")
    lines += ["", "## Reading the comparison", "",
              "The CNOT-depth guard is applied against the common-simplified comparator,",
              "not only the raw decomposition shown in the table. The starting circuit",
              "can have a lower energy than the selected earlier comparison checkpoint.", "",
              "![Raw, common-simplified, and compressed CNOT counts for one LiH pair](assets/lih-example.svg)", "",
              "For this LiH 1.50 Å pair, the raw CEO comparator has 112 CNOTs, the",
              "common-simplified comparator has 100, and the output has 65. Total and",
              "additional-search CNOT reductions are 42.0% and 35.0%, respectively.", "",
              "## Source and reconstruction", "",
              "This page and its example SVG are generated by",
              "`python3 tools/build_readme_assets.py` from the unchanged",
              "[recorded selection](../data/metadata/report-selection.json). Candidate IDs,",
              "full-precision values, common-simplified resources, and evidence paths remain",
              "in that metadata. The repository checks detect stale generated views.", "",
              "[Method](PROTOCOL.md) · [Data dictionary](DATA_DICTIONARY.md) ·",
              "[Reconstruct and verify the raw records](QUICKSTART.md)", ""]

    example = next(r for r in rows if r["molecule"] == "LiH" and r["distance_A"] == 1.5)
    entries = [("Raw CEO comparator", example["ceo"]["cnot"], "#F1F6FC"),
               ("After common simplification", example["common_resources"]["cnot"], "#FFFBEA"),
               ("Compressed circuit", example["child"]["cnot"], "#F2F9F2")]
    svg = ['<svg xmlns="http://www.w3.org/2000/svg" width="960" height="292" viewBox="0 0 960 292" role="img" aria-labelledby="title description">',
           '<title id="title">One saved LiH comparison at 1.50 angstrom</title>',
           '<desc id="description">CNOT count is separated into raw decomposition, common simplification, and additional search. All bars refer to one identified comparison pair.</desc>',
           '<rect width="960" height="292" fill="#FFFFFF"/>',
           '<g font-family="Arial, Helvetica, sans-serif" fill="#111111">',
           f'<text x="28" y="31" font-size="20" font-weight="700">LiH 1.50 Å · source step {example["root_step"]} · comparator step {example["comparator_step"]}</text>',
           '<text x="28" y="59" font-size="15">CNOT count under the recorded logical decomposition</text>']
    for index, (label, count, fill) in enumerate(entries):
        y = 85 + 54 * index
        width = 4.4 * count
        svg += [f'<text x="28" y="{y + 24}" font-size="16">{html.escape(label)}</text>',
                f'<rect x="306" y="{y}" width="{width:.1f}" height="36" rx="5" fill="{fill}" stroke="#111111" stroke-width="1.2"/>',
                f'<text x="{318 + width:.1f}" y="{y + 24}" font-size="18" font-weight="700">{count}</text>']
    gap = example["delta_energy_Ha"] * 1000
    svg += [f'<text x="28" y="260" font-size="15">Energy change: {gap:+.5f} mHa · common/output CNOT depth: {example["common_resources"]["cnot_depth"]}/{example["child"]["cnot_depth"]}</text>',
            '</g>', '</svg>', '']
    return {"docs/RESULTS.md": "\n".join(lines), "docs/assets/lih-example.svg": "\n".join(svg)}


def build(root=ROOT, check=False):
    stale = []
    for name, content in generated_files(root).items():
        path = Path(root) / name
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        raise ValueError("Stale generated documentation: " + ", ".join(stale))
    return {"status": "PASS", "generated_views": 2, "current_conditions": 22,
            "mode": "check" if check else "build", "new_molecular_evaluations": 0}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    print(json.dumps(build(check=args.check)))


if __name__ == "__main__":
    main()
